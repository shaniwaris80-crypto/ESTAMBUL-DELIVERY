-- STAGING FIRST. Do not run against live Supabase until a restorable database
-- backup and coordinated release plan have been confirmed.
-- "Reiniciar operaciones" hides old orders from active dashboards but preserves
-- EVERY original order, client, historical payment, chat, SMS receipt and audit row.
BEGIN;
CREATE TABLE IF NOT EXISTS public.ed_operations_epoch (
  account_id uuid PRIMARY KEY REFERENCES public.ed_accounts(id) ON DELETE CASCADE,
  started_at timestamptz NOT NULL DEFAULT '1970-01-01 00:00:00+00'::timestamptz,
  previous_started_at timestamptz,
  revision integer NOT NULL DEFAULT 0 CHECK(revision>=0),
  changed_by uuid REFERENCES auth.users(id),
  changed_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.ed_operations_epoch ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ed_operations_epoch FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.ed_operations_epoch TO authenticated;
GRANT ALL ON public.ed_operations_epoch TO service_role;
DROP POLICY IF EXISTS ed_operations_epoch_member_read ON public.ed_operations_epoch;
CREATE POLICY ed_operations_epoch_member_read ON public.ed_operations_epoch
 FOR SELECT TO authenticated USING (
 EXISTS(SELECT 1 FROM public.ed_members m
  WHERE m.account_id=ed_operations_epoch.account_id
  AND m.user_id=(select auth.uid()) AND m.active)
);

CREATE TABLE IF NOT EXISTS private.ed_operations_epoch_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id uuid NOT NULL REFERENCES public.ed_accounts(id),
 operation text NOT NULL CHECK(operation IN ('reset','restore')),
 performed_by uuid NOT NULL REFERENCES auth.users(id),
 old_started_at timestamptz NOT NULL,
 new_started_at timestamptz NOT NULL,
 performed_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE private.ed_operations_epoch_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON private.ed_operations_epoch_audit FROM PUBLIC,anon,authenticated;
GRANT SELECT ON private.ed_operations_epoch_audit TO service_role;

CREATE OR REPLACE FUNCTION public.ed_reset_operations_view(
 p_account_id uuid,p_confirmation text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $func$
DECLARE prior_time timestamptz;new_time timestamptz;v_user uuid;count_old integer;
BEGIN
 v_user=(select auth.uid());
 IF v_user IS NULL OR p_account_id IS NULL OR p_confirmation IS DISTINCT FROM 'REINICIAR'
 THEN RAISE EXCEPTION 'Confirmacion incorrecta'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.ed_members m
  WHERE m.account_id=p_account_id AND m.user_id=v_user AND m.active AND m.role='admin')
 THEN RAISE EXCEPTION 'Solo el administrador puede reiniciar operaciones';END IF;
 -- Serialise operation cutoff changes for the selected restaurant.
 PERFORM 1 FROM public.ed_accounts a WHERE a.id=p_account_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Cuenta no encontrada';END IF;
 -- Never silently remove an ongoing delivery from the Rider or manager screen.
 IF EXISTS(SELECT 1 FROM public.ed_orders o
   WHERE o.account_id=p_account_id AND o.rider_id IS NOT NULL
   AND o.status IN ('asignado','recogido','en_ruta'))
 THEN RAISE EXCEPTION 'Hay repartos asignados en curso. Finaliza primero las entregas';END IF;
 SELECT e.started_at INTO prior_time FROM public.ed_operations_epoch e
 WHERE e.account_id=p_account_id;
 prior_time=coalesce(prior_time,'1970-01-01 00:00:00+00'::timestamptz);
 new_time=clock_timestamp();
 SELECT count(*) INTO count_old FROM public.ed_orders o
 WHERE o.account_id=p_account_id AND o.created_at>=prior_time AND o.created_at<new_time;
 INSERT INTO public.ed_operations_epoch(account_id,started_at,previous_started_at,revision,changed_by,changed_at)
 VALUES(p_account_id,new_time,prior_time,1,v_user,new_time)
 ON CONFLICT(account_id) DO UPDATE
 SET started_at=excluded.started_at,
 previous_started_at=public.ed_operations_epoch.started_at,
 revision=public.ed_operations_epoch.revision+1,
 changed_by=excluded.changed_by,changed_at=excluded.changed_at;
 INSERT INTO private.ed_operations_epoch_audit(account_id,operation,performed_by,old_started_at,new_started_at)
 VALUES(p_account_id,'reset',v_user,prior_time,new_time);
 RETURN jsonb_build_object('ok',true,'archived_from_view',count_old,'since',new_time,
   'restorable',true,'message','Vista diaria reiniciada. Los datos históricos permanecen guardados.');
END $func$;
REVOKE ALL ON FUNCTION public.ed_reset_operations_view(uuid,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.ed_reset_operations_view(uuid,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.ed_restore_operations_view(
 p_account_id uuid,p_confirmation text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $func$
DECLARE before_time timestamptz;restored_time timestamptz;v_user uuid;
BEGIN
 v_user=(select auth.uid());
 IF v_user IS NULL OR p_account_id IS NULL OR p_confirmation IS DISTINCT FROM 'RESTAURAR'
 THEN RAISE EXCEPTION 'Confirmacion incorrecta';END IF;
 IF NOT EXISTS(SELECT 1 FROM public.ed_members m
  WHERE m.account_id=p_account_id AND m.user_id=v_user AND m.active AND m.role='admin')
 THEN RAISE EXCEPTION 'Solo el administrador puede restaurar operaciones'; END IF;
 PERFORM 1 FROM public.ed_accounts a WHERE a.id=p_account_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Cuenta no encontrada';END IF;
 SELECT e.started_at,e.previous_started_at INTO before_time,restored_time
 FROM public.ed_operations_epoch e WHERE e.account_id=p_account_id FOR UPDATE;
 IF before_time IS NULL OR restored_time IS NULL
 THEN RAISE EXCEPTION 'No hay un reinicio anterior disponible para restaurar';END IF;
 UPDATE public.ed_operations_epoch SET started_at=restored_time,previous_started_at=NULL,
  revision=revision+1,changed_at=clock_timestamp(),changed_by=v_user
 WHERE account_id=p_account_id;
 INSERT INTO private.ed_operations_epoch_audit(account_id,operation,performed_by,old_started_at,new_started_at)
 VALUES(p_account_id,'restore',v_user,before_time,restored_time);
 RETURN jsonb_build_object('ok',true,'since',restored_time,
  'message','Vista operativa anterior restaurada. Nunca se borraron los pedidos.');
END $func$;
REVOKE ALL ON FUNCTION public.ed_restore_operations_view(uuid,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.ed_restore_operations_view(uuid,text) TO authenticated;
COMMIT;
